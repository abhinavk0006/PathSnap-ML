"""Step 8: write results/SUMMARY.md from the saved result files (no numbers are typed by hand)."""
import _setup  # noqa: F401
import json

import pandas as pd

from pathsnap.common import load_config, resolve


def main():
    cfg = load_config()
    res = resolve(cfg, "results")
    out = ["# PathSnap results summary (generated by scripts/08_summary.py from results/**)\n"]
    inv = res / "eda" / "dataset_summary_by_partition.csv"
    if inv.exists():
        out += ["## Dataset (results/eda)\n", pd.read_csv(inv, index_col=0).to_markdown(), "\n"]
    cmp_ = res / "models" / "comparison_table.csv"
    if cmp_.exists():
        df = pd.read_csv(cmp_)
        cols = ["Model", "Algorithm family", "CV Macro F1 (mean)", "CV Top-1 (mean)", "Student Top-1", "Student Macro F1 (candidate)",
                "Student log loss", "Route continuity (h=3)", "Train time (s)", "Inference (ms / 1000 fixes)"]
        out += ["## Model comparison (5-fold grouped CV on training trips; student-test = 10 trips)\n",
                df[cols].round(4).to_markdown(index=False), "\n"]
    t = res / "hpo" / "tuned_vs_untuned.json"
    if t.exists():
        d = json.loads(t.read_text())
        bp = json.loads((res / "hpo" / "best_params.json").read_text())
        tab = pd.DataFrame({"untuned": d["untuned"], "tuned": d["tuned"]})
        out += [f"## Bayesian optimisation ({d['model']}, {bp['n_trials']} trials, objective: {bp['objective']})\n",
                "Best parameters: `" + json.dumps(bp["best_params"]) + "`\n", tab.round(4).to_markdown(), "\n"]
    h = res / "hmm" / "student_summary.json"
    if h.exists():
        s = json.loads(h.read_text())["summary"]
        out += ["## Classifier-only vs classifier + HMM/Viterbi (student-test)\n", pd.DataFrame(s).round(4).to_markdown(), "\n"]
        cfgp = resolve(cfg, "models") / "hmm_config.json"
        if cfgp.exists():
            out += ["Decoder parameters: `" + json.dumps(json.loads(cfgp.read_text())["params"]) + "`\n"]
    (res / "SUMMARY.md").write_text("\n".join(out))
    print("wrote", res / "SUMMARY.md")


if __name__ == "__main__":
    main()
